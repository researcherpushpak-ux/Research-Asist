import pandas as pd
import streamlit as st

from ev_research.analysis import (data_io, descriptive, efa, inferential, mediation, plssem_prep,
                                  reliability)
from ev_research.analysis.result import AnalysisError
from ev_research.report.report_builder import (CATEGORY_DESCRIPTIVE, CATEGORY_PREPARATION,
                                               CATEGORY_STATISTICAL)
from ev_research.ui import (SAMPLE_DIR, groups_to_text, page_header, parse_groups, show_result)
from ev_research.viz import charts

st.set_page_config(page_title="Data Analysis", layout="wide")
page_header("Module 2 - Questionnaire Data Analysis",
            "Upload survey data (CSV or Excel; one row per respondent, one column per question).")
S = st.session_state


def run(func, *args, **kwargs):
    """Run an analysis and show a readable error instead of a crash."""
    try:
        return func(*args, **kwargs)
    except AnalysisError as exc:
        st.error(str(exc))
    except Exception as exc:
        st.error(f"The analysis could not be completed: {exc}")
    return None


def set_dataset(df: pd.DataFrame, name: str, synthetic: bool) -> None:
    S["df_raw"], S["df"], S["df_name"], S["df_synthetic"] = df, df.copy(), name, synthetic
    S["data_notes"] = []
    S["inspection"] = data_io.inspect(df)
    S["groups"] = data_io.detect_item_groups(data_io.detect_likert_columns(df))
    for k in [k for k in S.keys() if str(k).startswith("res_")]:
        del S[k]


# ---------------------------------------------------------------- load data
with st.expander("1. Load data", expanded=S["df"] is None):
    up = st.file_uploader("Upload dataset", type=["csv", "xlsx", "xls"])
    sheet = 0
    if up is not None and up.name.lower().endswith((".xlsx", ".xls")):
        try:
            names = data_io.excel_sheet_names(up.getvalue())
            sheet = st.selectbox("Sheet", names)
        except AnalysisError as exc:
            st.error(str(exc))
    c1, c2 = st.columns(2)
    if c1.button("Load uploaded file", disabled=up is None, type="primary"):
        df = run(data_io.load_dataset, up.getvalue(), up.name, sheet)
        if df is not None:
            set_dataset(df, up.name, False)
            st.success(f"Loaded {df.shape[0]} rows x {df.shape[1]} columns.")
    if c2.button("Load SYNTHETIC sample dataset (for learning only)"):
        path = SAMPLE_DIR / "ev_survey_synthetic.csv"
        set_dataset(data_io.load_dataset(path.read_bytes(), path.name), path.name + " (SYNTHETIC)", True)
        st.warning("Synthetic data loaded. It was generated by a random model and is not real evidence.")

df = S["df"]
if df is None:
    st.stop()
if S["df_synthetic"]:
    st.warning("You are working with the SYNTHETIC sample dataset. Results are for learning the software only.")
st.markdown(f"**Current dataset:** {S['df_name']}: {df.shape[0]} rows x {df.shape[1]} columns")
num_cols = data_io.numeric_columns(df)
ana_cols = data_io.analysis_columns(df)        # numeric without ID-like columns, for defaults
all_cols = list(df.columns)

tabs = st.tabs(["Inspect & prepare", "Descriptives", "Frequencies", "Reliability", "Factor analysis (EFA)",
                "Correlation", "Regression", "ANOVA", "Mediation", "PLS-SEM preparation"])

# ---------------------------------------------------------------- inspect & prepare
with tabs[0]:
    show_result(data_io.inspect(df), CATEGORY_DESCRIPTIVE, "inspect")
    st.caption(data_io.little_mcar_note())
    st.markdown("---")
    st.markdown("#### Prepare the data")
    st.markdown("Changes apply to the working copy; the uploaded file is not changed. Every step is recorded for the report.")
    with st.form("missing"):
        cols = st.multiselect("Variables for missing-value handling", num_cols, default=[i for v in S["groups"].values() for i in v if i in num_cols])
        method = st.radio("Method", ["listwise", "mean", "median"], horizontal=True,
                          help="Listwise: drop rows with any missing value in the selected variables (default, transparent). "
                               "Mean/median: replace missing values; this reduces variance and should be reported.")
        if st.form_submit_button("Apply missing-value handling") and cols:
            out = run(data_io.handle_missing, df, cols, method)
            if out:
                S["df"], note = out
                S["data_notes"].append(note)
                st.success(note)
                st.rerun()
    with st.form("reverse"):
        rc = st.multiselect("Reverse-code these items (negatively worded questions)", num_cols)
        c1, c2 = st.columns(2)
        lo = c1.number_input("Scale minimum", value=1, step=1)
        hi = c2.number_input("Scale maximum", value=5, step=1)
        if st.form_submit_button("Reverse-code") and rc:
            out = run(data_io.reverse_code, df, rc, int(lo), int(hi))
            if out is not None:
                S["df"] = out
                S["data_notes"].append(f"Reverse-coded on a {int(lo)}-{int(hi)} scale: {', '.join(rc)}.")
                st.success("Done.")
                st.rerun()
    st.markdown("#### Constructs (scales)")
    st.markdown("One construct per line: `NAME: item1, item2, item3`. Auto-detected from column names such as ATT1, ATT2 ... Edit if needed.")
    txt = st.text_area("Construct definitions", groups_to_text(S["groups"]), height=160)
    c1, c2 = st.columns(2)
    if c1.button("Save construct definitions"):
        g = parse_groups(txt)
        missing = [i for v in g.values() for i in v if i not in df.columns]
        if missing:
            st.error(f"These items are not columns in the dataset: {missing}")
        else:
            S["groups"] = g
            st.success(f"Saved {len(g)} constructs.")
    if c2.button("Compute construct mean scores (adds columns)", disabled=not S["groups"]):
        scores = data_io.composite_scores(df, S["groups"])
        clash = [c for c in scores.columns if c in df.columns]
        S["df"] = pd.concat([df.drop(columns=clash), scores], axis=1)
        S["data_notes"].append("Construct scores = mean of items (computed when at least half the items were answered): "
                               + ", ".join(S["groups"]) + ".")
        st.success("Added: " + ", ".join(scores.columns))
        st.rerun()
    if S["data_notes"]:
        st.markdown("**Data preparation log**")
        for n in S["data_notes"]:
            st.markdown(f"- {n}")
    if st.button("Reset to the uploaded data"):
        S["df"], S["data_notes"] = S["df_raw"].copy(), []
        st.rerun()
    st.download_button("Download working dataset (CSV)", df.to_csv(index=False).encode("utf-8"), "working_dataset.csv", "text/csv")

# ---------------------------------------------------------------- descriptives
with tabs[1]:
    cols = st.multiselect("Numeric variables", num_cols, default=ana_cols[:8], key="desc_cols")
    if st.button("Run descriptive statistics", key="b_desc"):
        S["res_desc"] = run(descriptive.descriptives, df, cols)
    if S.get("res_desc"):
        show_result(S["res_desc"], CATEGORY_DESCRIPTIVE, "desc")

# ---------------------------------------------------------------- frequencies
with tabs[2]:
    cat_cols = data_io.categorical_columns(df) or all_cols
    col = st.selectbox("Variable", cat_cols, key="freq_col")
    if st.button("Run frequency table", key="b_freq"):
        S["res_freq"] = run(descriptive.frequencies, df, col)
    if S.get("res_freq"):
        show_result(S["res_freq"], CATEGORY_DESCRIPTIVE, "freq")

# ---------------------------------------------------------------- reliability
with tabs[3]:
    mode = st.radio("Scope", ["All defined constructs", "One scale (detailed item statistics)"], horizontal=True)
    if mode == "All defined constructs":
        if not S["groups"]:
            st.info("Define constructs in 'Inspect & prepare' first.")
        elif st.button("Compute Cronbach's alpha for all constructs"):
            S["res_rel_all"] = run(reliability.reliability_table, df, S["groups"])
        if S.get("res_rel_all"):
            show_result(S["res_rel_all"], CATEGORY_DESCRIPTIVE, "rel_all")
    else:
        names = list(S["groups"])
        name = st.selectbox("Construct", names + ["(custom selection)"])
        items = st.multiselect("Items", num_cols, default=S["groups"].get(name, []), key=f"rel_items_{name}")
        if st.button("Run reliability analysis"):
            S["res_rel"] = run(reliability.reliability_analysis, df, items, name if name in names else "Custom scale")
        if S.get("res_rel"):
            show_result(S["res_rel"], CATEGORY_DESCRIPTIVE, "rel")

# ---------------------------------------------------------------- EFA
with tabs[4]:
    st.markdown("EFA is appropriate when you want to explore whether items group into the expected factors. Use item-level (not construct-score) columns.")
    default_items = [i for v in S["groups"].values() for i in v]
    items = st.multiselect("Items", num_cols, default=default_items, key="efa_items")
    if st.button("1. Check suitability (KMO, Bartlett, eigenvalues)"):
        r = run(efa.suitability, df, items)
        if r:
            r.figures["Scree plot"] = charts.to_png(charts.scree_plot(r.tables["Eigenvalues"]["Eigenvalue"].tolist()))
            S["res_efa_s"] = r
    if S.get("res_efa_s"):
        show_result(S["res_efa_s"], CATEGORY_STATISTICAL, "efa_s")
    st.markdown("---")
    c1, c2, c3, c4 = st.columns(4)
    nf = c1.number_input("Number of factors", 1, max(1, len(items) - 1), min(max(1, len(S["groups"]) or 1), max(1, len(items) - 1)))
    rot = c2.selectbox("Rotation", ["oblimin", "promax", "varimax", "none"], help="Oblique (oblimin/promax) lets factors correlate, which is usual for attitude constructs.")
    meth = c3.selectbox("Extraction", ["minres", "ml", "principal"])
    cut = c4.number_input("Loading cut-off", 0.2, 0.8, 0.4, 0.05)
    if st.button("2. Run EFA"):
        S["res_efa"] = run(efa.run_efa, df, items, int(nf), rot, meth, float(cut))
    if S.get("res_efa"):
        show_result(S["res_efa"], CATEGORY_STATISTICAL, "efa")

# ---------------------------------------------------------------- correlation
with tabs[5]:
    default = [g for g in S["groups"] if g in df.columns] or ana_cols[:6]
    cols = st.multiselect("Variables", num_cols, default=default, key="corr_cols")
    meth = st.radio("Method", ["pearson", "spearman"], horizontal=True, help="Spearman is rank-based: use it for ordinal single items or non-normal data.")
    if st.button("Run correlation analysis"):
        r = run(inferential.correlation, df, cols, meth)
        if r:
            r.figures["Correlation heatmap"] = charts.to_png(charts.correlation_heatmap(r.raw["r"], r.raw["p"]))
            S["res_corr"] = r
    if S.get("res_corr"):
        show_result(S["res_corr"], CATEGORY_STATISTICAL, "corr")

# ---------------------------------------------------------------- regression
with tabs[6]:
    if not any(g in df.columns for g in S["groups"]):
        st.info("Tip: compute construct mean scores in 'Inspect & prepare' to regress constructs (e.g. PI on ATT, SN, PBC).")
    dv = st.selectbox("Dependent variable (outcome)", num_cols, index=num_cols.index("PI") if "PI" in num_cols else 0, key="reg_dv")
    ivs = st.multiselect("Independent variables (predictors)", [c for c in all_cols if c != dv], key="reg_iv")
    cats = st.multiselect("Which predictors are categorical? (dummy-coded)", ivs, default=[c for c in ivs if c not in num_cols], key="reg_cat")
    if st.button("Run regression"):
        S["res_reg"] = run(inferential.regression, df, dv, ivs, cats)
    if S.get("res_reg"):
        show_result(S["res_reg"], CATEGORY_STATISTICAL, "reg")

# ---------------------------------------------------------------- ANOVA
with tabs[7]:
    st.markdown("Compare a numeric outcome across groups of a categorical variable (e.g. purchase intention by income group).")
    dv = st.selectbox("Outcome (numeric)", num_cols, key="anova_dv")
    grp = st.selectbox("Grouping variable", data_io.categorical_columns(df) or all_cols, key="anova_g")
    if st.button("Run ANOVA"):
        S["res_anova"] = run(inferential.one_way_anova, df, dv, grp)
    if S.get("res_anova"):
        show_result(S["res_anova"], CATEGORY_STATISTICAL, "anova")

# ---------------------------------------------------------------- mediation
with tabs[8]:
    st.markdown("Tests whether X affects Y **through** a mediator M (X -> M -> Y). Use construct scores. "
                "Mediation should be justified by theory; the test cannot establish causal order.")
    c1, c2, c3 = st.columns(3)
    x = c1.selectbox("X (predictor)", num_cols, key="med_x")
    m = c2.selectbox("M (mediator)", num_cols, key="med_m")
    y = c3.selectbox("Y (outcome)", num_cols, key="med_y")
    covs = st.multiselect("Covariates (optional, numeric)", [c for c in num_cols if c not in (x, m, y)], key="med_cov")
    c1, c2 = st.columns(2)
    nb = c1.number_input("Bootstrap samples", 500, 50000, 5000, 500)
    seed = c2.number_input("Random seed (for reproducibility)", 0, 10**9, 12345)
    if st.button("Run mediation analysis"):
        with st.spinner("Bootstrapping..."):
            r = run(mediation.simple_mediation, df, x, m, y, covs, int(nb), 0.95, int(seed))
        if r:
            ind = r.tables["Indirect effect"].iloc[0]
            r.figures["Bootstrap distribution of the indirect effect"] = charts.to_png(
                charts.bootstrap_histogram(r.raw["boot"], ind.iloc[2], ind.iloc[3], f"Indirect effect {x} -> {m} -> {y}"))
            S["res_med"] = r
    if S.get("res_med"):
        show_result(S["res_med"], CATEGORY_STATISTICAL, "med")

# ---------------------------------------------------------------- PLS-SEM prep
with tabs[9]:
    st.error("**This application does not estimate PLS-SEM models.** This tab prepares your data and model for SmartPLS or R (seminr), "
             "and computes checks that do not require PLS estimation. Report the PLS results from that software, not from here.")
    if not S["groups"]:
        st.info("Define constructs in 'Inspect & prepare' first.")
    else:
        st.markdown("**Structural model**: one path per line, `FROM -> TO` (e.g. `ATT -> PI`).")
        default_paths = "\n".join(f"{g} -> PI" for g in S["groups"] if g != "PI") if "PI" in S["groups"] else ""
        ptxt = st.text_area("Paths", default_paths, height=140)
        paths = []
        for line in ptxt.splitlines():
            if "->" in line:
                a, b = [s.strip() for s in line.split("->", 1)]
                if a and b:
                    paths.append((a, b))
        mp = st.number_input("Smallest path coefficient you expect to detect (for sample-size guidance)", 0.05, 0.9, 0.15, 0.01)
        if st.button("Run PLS-SEM preparation checks"):
            r = run(plssem_prep.prepare, df, S["groups"], paths, float(mp))
            if r:
                S["res_pls"], S["pls_paths"] = r, paths
        if S.get("res_pls"):
            show_result(S["res_pls"], CATEGORY_PREPARATION, "pls")
            st.markdown("#### Exports for your PLS software")
            miss = st.radio("Missing values in export", ["listwise", "code"], horizontal=True,
                            format_func=lambda v: "Remove incomplete rows" if v == "listwise" else "Write as -99")
            extra = st.multiselect("Extra columns to include (e.g. grouping variables for MGA)", [c for c in all_cols if c not in sum(S["groups"].values(), [])])
            try:
                data, note = plssem_prep.export_smartpls_csv(df, S["groups"], extra, miss)
                st.caption(note)
                st.download_button("Download data for SmartPLS (CSV)", data, "pls_data.csv", "text/csv")
            except AnalysisError as exc:
                st.error(str(exc))
            script = plssem_prep.seminr_script(S["groups"], S.get("pls_paths", []))
            st.download_button("Download R script template (seminr) - NOT tested by this app", script.encode("utf-8"), "pls_model_seminr.R", "text/plain")
            with st.expander("Preview R script"):
                st.code(script, language="r")
